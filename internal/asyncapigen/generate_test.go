package asyncapigen

import (
	"strings"
	"testing"
)

const spec = `{
  "asyncapi": "3.0.0",
  "components": {"schemas": {
    "Event": {"type": "object", "x-go-type": "wire.Event", "description": "One event.", "required": ["id", "data"],
      "properties": {
        "id": {"type": "string", "description": "Its id, a long description that wraps over more than one line of a Go comment for sure."},
        "traceId": {"type": "string"},
        "count": {"type": "integer"}, "ratio": {"type": "number"}, "done": {"type": "boolean"},
        "tags": {"type": "array", "items": {"type": "string"}},
        "data": {"$ref": "#/components/schemas/EventData"}}},
    "EventData": {"type": "object", "x-go-type": "wire.EventData", "properties": {"kmpKey": {"type": "string"}}},
    "Other": {"type": "object", "x-go-type": "other.Other", "properties": {"x": {"type": "string"}}},
    "Plain": {"type": "object", "properties": {"x": {"type": "string"}}}
  }}
}`

func TestGenerateWritesOneFilePerSchemaOfThePackage(t *testing.T) {
	files, err := Generate([]byte(spec), "spec.json", "wire")
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 2 {
		t.Fatalf("files = %d", len(files))
	}
	event := string(files["event_gen.go"])
	for _, want := range []string{
		"// Code generated by asyncapigen from spec.json; DO NOT EDIT.",
		"package wire",
		"// One event.\ntype Event struct {",
		"ID string `json:\"id\"`",
		"TraceID string `json:\"traceId,omitempty\"`",
		"Count int `json:\"count,omitempty\"`",
		"Ratio float64",
		"Done bool",
		"Tags []string",
		"Data EventData `json:\"data\"`",
		"// Its id, a long description",
	} {
		if !strings.Contains(strings.Join(strings.Fields(event), " "), strings.Join(strings.Fields(want), " ")) {
			t.Errorf("event_gen.go has no %q:\n%s", want, event)
		}
	}
	if strings.Index(event, "TraceID") > strings.Index(event, "Count") {
		t.Error("the fields are not in the spec's order")
	}
	data := string(files["event_data_gen.go"])
	if !strings.Contains(data, "// EventData is the schema EventData of the spec.") || !strings.Contains(data, "KMPKey") {
		t.Errorf("event_data_gen.go:\n%s", data)
	}
}

func TestGenerateRefusesWhatItCannotWrite(t *testing.T) {
	cases := map[string]string{
		"not json":    `{`,
		"trailing":    `{"asyncapi": "3.0.0"} {}`,
		"version 2":   `{"asyncapi": "2.6.0", "components": {"schemas": {}}}`,
		"no schemas":  `{"asyncapi": "3.0.0"}`,
		"none of it":  `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "other.A", "properties": {"x": {"type": "string"}}}}}}`,
		"not object":  `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "string", "x-go-type": "wire.A"}}}}`,
		"no fields":   `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "wire.A"}}}}`,
		"required":    `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "wire.A", "required": ["y"], "properties": {"x": {"type": "string"}}}}}}`,
		"inline":      `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "wire.A", "properties": {"x": {"type": "object"}}}}}}`,
		"foreign ref": `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "wire.A", "properties": {"x": {"$ref": "#/components/schemas/B"}}}, "B": {"type": "object", "properties": {"y": {"type": "string"}}}}}}`,
		"bad array":   `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "wire.A", "properties": {"x": {"type": "array", "items": {"type": "object"}}}}}}}`,
		"bad nesting": `{"asyncapi": "3.0.0", "components": {"schemas": {"A": {"type": "object", "x-go-type": "wire.A", "properties": {"x": [}}}}}`,
	}
	for name, raw := range cases {
		if _, err := Generate([]byte(raw), "s.json", "wire"); err == nil {
			t.Errorf("%s: generated", name)
		}
	}
}

