def svg(name: str, grid: str) -> str:
    rows = [r for r in grid.strip("\n").split("\n")]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise SystemExit(f"{name}: the grid must be 16 rows of 16 cells")
    runs = []
    for y, row in enumerate(rows):
        x = 0
        while x < 16:
            if row[x] == "#":
                start = x
                while x < 16 and row[x] == "#":
                    x += 1
                runs.append(f"M{start} {y}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    # One path, so a scaled glyph has no seams between its rows.
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16">'
        f'<title>{name}</title><path fill="#000000" d="{"".join(runs)}"/></svg>\n'
    )


def main() -> None:
    here = Path(__file__).resolve().parent
    for name, grid in ICONS.items():
        (here / f"{name}.svg").write_text(svg(name, grid))
    print(f"wrote {len(ICONS)} icons to {here}")


if __name__ == "__main__":
    main()
