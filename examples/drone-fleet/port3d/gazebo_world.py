#!/usr/bin/env python3
"""Write the gz sim (Harmonic) world of Maasvlakte 2 and its port model.

    python3 gazebo_world.py [--features build/features.json] [--dir ../gz]

  ../gz/models/maasvlakte2/model.config, model.sdf   the port, static: the
      mesh build_scene.py exported with --gazebo (meshes/port.glb) is what
      the cameras and lidars see; what a vehicle stands on is simpler, the
      sea a plane at 0 and the land's top (meshes/ground.obj, prepare.py's
      land triangulated) at GROUND_M. Colliding with the whole port's mesh
      cost more than the physics step had: six quads on it ran at 0.07 x
      real time. A crane or a building stops no vehicle; the lidars still
      see it.
  ../gz/models/maasvlakte2/meshes/ground.obj   the land's top
  ../gz/worlds/maasvlakte2.sdf   the world: the port, a sun, the systems an
      ArduPilot SITL vehicle needs (physics, sensors, IMU, NavSat, air
      pressure, magnetometer), and the spherical coordinates that put the
      world's origin at area.ORIGIN with X east, Y north (ENU), the sea at 0

    GZ_SIM_RESOURCE_PATH=../gz/models gz sim ../gz/worlds/maasvlakte2.sdf

Checked with gz sim 8.11 (Harmonic, osrf/ros:jazzy-desktop-full), server
only: a ball dropped at the origin rests on the quay at 5 m, one dropped on
the Prinses Amaliahaven at the sea's 0, with dartsim.
"""

import argparse
import json
import os
import sys

import area

MODEL = """<?xml version="1.0"?>
<!-- Generated by gazebo_world.py. The port of Maasvlakte 2 from OpenStreetMap
     data (c) OpenStreetMap contributors, ODbL. -->
<sdf version="1.9">
  <model name="maasvlakte2">
    <static>true</static>
    <link name="port">
      <!-- glTF is Y-up and gz sim loads it as it is: turned +90 degrees about X,
           the mesh's X, Y, Z are east, north, up. -->
      <visual name="visual">
        <pose>0 0 0 1.5707963 0 0</pose>
        <geometry><mesh><uri>model://maasvlakte2/meshes/port.glb</uri></mesh></geometry>
      </visual>
      <!-- What a vehicle stands on: the sea's top at 0, the land's top at {ground} m. -->
      <collision name="sea">
        <pose>0 0 -5 0 0 0</pose>
        <geometry><box><size>20000 20000 10</size></box></geometry>
      </collision>
      <collision name="ground">
        <geometry><mesh><uri>model://maasvlakte2/meshes/ground.obj</uri></mesh></geometry>
      </collision>
    </link>
  </model>
</sdf>
"""

CONFIG = """<?xml version="1.0"?>
<model>
  <name>maasvlakte2</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>AXLR Bots port fleet example</name></author>
  <description>Maasvlakte 2, Port of Rotterdam: {w} to {e} E, {s} to {n} N, in metres east and north of
    {lat} N {lon} E; the sea at 0, the quays at {ground} m. OpenStreetMap data (c) OpenStreetMap
    contributors, ODbL. Generated by examples/drone-fleet/port3d.</description>
</model>
"""

WORLD = """<?xml version="1.0"?>
<!-- Generated by gazebo_world.py: Maasvlakte 2 for ArduPilot SITL in gz sim Harmonic.
     GZ_SIM_RESOURCE_PATH=models gz sim worlds/maasvlakte2.sdf -->
<sdf version="1.9">
  <world name="maasvlakte2">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>
    <plugin filename="gz-sim-air-pressure-system" name="gz::sim::systems::AirPressure"/>
    <plugin filename="gz-sim-magnetometer-system" name="gz::sim::systems::Magnetometer"/>

    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.62 0.74 0.88 1</background>
      <grid>false</grid>
    </scene>

    <!-- The world's origin is {lat} N {lon} E at sea level; X east, Y north. -->
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{lat}</latitude_deg>
      <longitude_deg>{lon}</longitude_deg>
      <elevation>0</elevation>
      <heading_deg>0</heading_deg>
    </spherical_coordinates>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 500 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse>
      <specular>0.3 0.3 0.3 1</specular>
      <direction>0.4 0.6 -0.7</direction>
    </light>

    <include>
      <uri>model://maasvlakte2</uri>
      <name>port</name>
      <pose>0 0 0 0 0 0</pose>
    </include>
  </world>
</sdf>
"""


def ground_obj(land, height):
    """The land's top as a Wavefront OBJ: prepare.py's triangles at height,
    X east, Y north, Z up, facing up, with their normal."""
    lines = ["# Generated by gazebo_world.py: the land's top of Maasvlakte 2, metres east, north, up.",
             "# OpenStreetMap data (c) OpenStreetMap contributors, ODbL.",
             # dartsim's ODE collision reads the normals and crashes without them.
             "vn 0 0 1"]
    base = 1
    for p in land:
        tv, t = p.get("tv") or [], p.get("t") or []
        lines += [f"v {tv[i]} {tv[i + 1]} {height}" for i in range(0, len(tv), 2)]
        for i in range(0, len(t), 3):
            a, b, c = (base + t[i + k] for k in range(3))
            ax, ay, bx, by, cx, cy = (tv[2 * (j - base) + k] for j in (a, b, c) for k in (0, 1))
            if (bx - ax) * (cy - ay) - (by - ay) * (cx - ax) < 0:
                b, c = c, b
            lines.append(f"f {a}//1 {b}//1 {c}//1")
        base += len(tv) // 2
    return "\n".join(lines) + "\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--features", default=os.path.join(here, "build", "features.json"))
    ap.add_argument("--dir", default=os.path.join(here, "..", "gz"))
    args = ap.parse_args()
    with open(args.features) as fh:
        land = json.load(fh)["land"]
    if not all(p.get("t") for p in land):
        sys.exit(f"{args.features}: the land has no triangles; run prepare.py again")
    lat, lon = area.ORIGIN
    s, w, n, e = area.BBOX
    model_dir = os.path.join(args.dir, "models", "maasvlakte2")
    os.makedirs(os.path.join(model_dir, "meshes"), exist_ok=True)
    os.makedirs(os.path.join(args.dir, "worlds"), exist_ok=True)
    with open(os.path.join(model_dir, "model.sdf"), "w") as f:
        f.write(MODEL.format(ground=area.GROUND_M))
    with open(os.path.join(model_dir, "meshes", "ground.obj"), "w") as f:
        f.write(ground_obj(land, area.GROUND_M))
    with open(os.path.join(model_dir, "model.config"), "w") as f:
        f.write(CONFIG.format(s=s, w=w, n=n, e=e, lat=lat, lon=lon, ground=area.GROUND_M))
    with open(os.path.join(args.dir, "worlds", "maasvlakte2.sdf"), "w") as f:
        f.write(WORLD.format(lat=lat, lon=lon))
    tris = sum(len(p["t"]) // 3 for p in land)
    print(f"{args.dir}: worlds/maasvlakte2.sdf, models/maasvlakte2/model.sdf (meshes/port.glb, meshes/ground.obj: {tris} triangles)")


if __name__ == "__main__":
    main()
